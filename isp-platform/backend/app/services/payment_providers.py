def render_invoice_pdf(
    invoice: BillingInvoice,
    client: Client,
    tenant_name: str,
    branding: Optional[dict[str, Any]] = None,
) -> bytes:
    brand = _coerce_branding(branding)
    header_name = brand["display_name"] or tenant_name
    item_lines = invoice.line_items or [{"description": invoice.plan_name, "quantity": 1, "amount": invoice.amount}]
    lines = [
        f"Invoice Number: {invoice.invoice_number}",
        f"Customer: {client.name} ({client.client_id})",
        f"Plan: {invoice.plan_name}",
        f"Issued At: {invoice.issued_at}",
        f"Due Date: {invoice.due_date}",
        f"Status: {invoice.status.value if hasattr(invoice.status, 'value') else invoice.status}",
        "",
        "Line Items:",
    ]
    for item in item_lines:
        lines.append(f"- {item.get('description', 'Item')} | Qty {item.get('quantity', 1)} | {invoice.currency} {_format_money(item.get('amount', invoice.amount))}")
    lines.extend(
        [
            "",
            f"Total: {invoice.currency} {_format_money(invoice.amount)}",
            f"Balance: {invoice.currency} {_format_money(invoice.balance)}",
            f"Support: {brand['support_email'] or 'Not configured'} {brand['support_phone'] or ''}".strip(),
            brand["footer_note"],
        ]
    )
    return _build_text_pdf(f"{header_name} Invoice", lines)


