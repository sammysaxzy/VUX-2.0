def build_activation_payload(client: Client, payment: BillingPayment, invoice: BillingInvoice) -> dict[str, Any]:
    return {
        "customer_id": client.client_id,
        "client_id": client.id,
        "payment_id": payment.payment_id,
        "invoice_number": invoice.invoice_number,
        "requested_at": datetime.utcnow().isoformat(),
        "status": "pending_service_activation",
        "integration": "existing_radius_interface_only",
    }


async def dispatch_service_activation(record: OperationRecord) -> ActivationDispatchResult:
    config = resolve_activation_service_config()
    endpoint = config["endpoint"]
    if not endpoint:
        return ActivationDispatchResult(
            success=False,
            status="pending",
            message="Activation service endpoint is not configured.",
        )

    headers = {"Content-Type": "application/json"}
    if config["api_key"]:
        headers["Authorization"] = f"Bearer {config['api_key']}"

    payload = {
        **(record.payload or {}),
        "operation_record_id": record.id,
        "record_key": record.record_key,
        "module": record.module,
    }
    try:
        async with httpx.AsyncClient(timeout=config["timeout_seconds"]) as http:
            response = await http.post(endpoint, headers=headers, json=payload)
            response.raise_for_status()
            data = response.json() if response.content else {}
    except Exception as exc:
        return ActivationDispatchResult(
            success=False,
            status="retry_pending",
            message=str(exc),
        )

    return ActivationDispatchResult(
        success=bool(data.get("accepted", True)),
        status=str(data.get("status") or ("completed" if data.get("completed") else "processing")),
        message=str(data.get("message") or "Activation request submitted successfully."),
        external_reference=data.get("external_reference") or data.get("job_id") or data.get("reference"),
        response_payload=data if isinstance(data, dict) else {"raw": data},
    )
